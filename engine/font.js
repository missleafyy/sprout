const cache = {};
function glyphImg(ch, col) {
  const k = ch + col;
  if (cache[k]) return cache[k];
  const gl = glyphs[ch] || glyphs['?'];
  const c = S.canvas(gl.w, 10), x = c.getContext('2d');
  x.fillStyle = col;
  gl.rows.forEach((r, y) => { for (let i = 0; i < r.length; i++) if (r[i] === '#') x.fillRect(i, y, 1, 1); });
  return (cache[k] = c);
}

// split "a {red}b{/} c" into [{t:'a ', c:null}, {t:'b', c:'red'}, {t:' c', c:null}]
function runs(str) {
  const out = []; let cur = null;
  str.split(/(\{\/?[a-z]*\})/).forEach(part => {
    const m = part.match(/^\{(\/?)([a-z]*)\}$/);
    if (m) { cur = m[1] || !m[2] ? null : m[2]; return; }
    if (part) out.push({ t: part, c: cur });
  });
  return out;
}
const strip = str => str.replace(/\{\/?[a-z]*\}/g, '');
const charW = ch => ch === ' ' ? SPACE + GAP : (glyphs[ch] || glyphs['?']).w + GAP;

const font = S.font = {
  colors: COLORS,
  lineH: 16,
  width(str) { let w = 0; for (const ch of strip(str)) w += charW(ch); return Math.max(0, w - GAP); },
  // word wrap to pixel width, keeping colour tags; returns array of lines
  wrap(str, maxW) {
    const lines = [];
    for (const para of String(str).split('\n')) {
      let line = '', lineW = 0, open = null;
      for (const word of para.split(' ')) {
        const ww = font.width(word);
        if (line && lineW + SPACE + GAP + ww > maxW) {
          lines.push(line + (open ? '{/}' : ''));
          line = open ? `{${open}}` : ''; lineW = 0;
        }
        line += (lineW || line.replace(/\{[a-z]*\}/g, '') ? ' ' : '') + word;
        lineW += (lineW ? SPACE + GAP : 0) + ww;
        const tags = word.match(/\{\/?[a-z]*\}/g);
        if (tags) for (const t of tags) open = t === '{/}' || t === '{}' ? null : t.slice(1, -1);
      }
      lines.push(line);
    }
    return lines;
  },
  // draw; returns width drawn. opt.count limits visible characters (typewriter)
  draw(g, str, x, y, opt = {}) {
    str = String(str);
    const base = opt.color || 'normal';
    const w = font.width(str);
    if (opt.align === 'center') x -= Math.floor(w / 2);
    else if (opt.align === 'right') x -= w;
    let n = opt.count == null ? Infinity : opt.count;
    let cx = x;
    for (const run of runs(str)) {
      const [fg, sh] = COLORS[run.c || base] || [run.c || base, null];
      const shadow = opt.shadow === false ? null : (opt.shadow || sh);
      for (const ch of run.t) {
        if (n-- <= 0) return w;
        if (ch !== ' ') {
          if (shadow) {
            const si = glyphImg(ch, shadow);
            g.img(si, cx + 1, y); g.img(si, cx, y + 1); g.img(si, cx + 1, y + 1);
          }
          g.img(glyphImg(ch, S.color(fg)), cx, y);
        }
        cx += charW(ch);
      }
    }
    return w;
  },
  length: str => strip(String(str)).length,
};
