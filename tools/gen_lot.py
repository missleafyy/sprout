"""The Lot: sand ground, dry scrub, asphalt with curbs and parking lines. Writes cracky/art_tiles.js."""
import sys, os, random
sys.path.insert(0, os.path.dirname(__file__))
from pxgen import *

# ---- sand ground: pebble clusters + the odd sage tuft, kept off the edges
PEBBLES = [["hS", "SD"], [".h.", "hSS", ".SD"], ["h", "S"], ["hS."], ["Sh", ".S"]]
SAGE = [[".u.u.", "uvVvu", ".VVV."], ["u.u", "vVv"]]
def sand(seed, n, sage):
    rnd = random.Random(seed); g = blank(16, 16, 's'); placed = []
    items = [rnd.choice(SAGE) for _ in range(sage)] + [rnd.choice(PEBBLES) for _ in range(n)]
    for t in items:
        for _ in range(200):
            w, h = len(t[0]), len(t)
            x, y = rnd.randint(1, 15 - w), rnd.randint(1, 15 - h)
            if any(abs(x - a) < 5 and abs(y - b) < 4 for a, b in placed): continue
            stamp(g, t, x, y); placed.append((x, y)); break
    return g
frames = {'sand0': sand(11, 3, 0), 'sand1': sand(12, 2, 0), 'sand2': sand(13, 2, 1), 'sand3': sand(14, 4, 0), 'sand4': sand(15, 1, 0)}

# ---- asphalt fill: speckle in small clusters + a hairline crack
def asphalt(seed, crack):
    rnd = random.Random(seed); g = blank(16, 16, 'b')
    for _ in range(7):
        x, y = rnd.randint(0, 15), rnd.randint(0, 15)
        g[y][x] = 'a' if rnd.random() < 0.7 else 'c'
    if crack:
        x, y = 3, 4
        for dx, dy in [(0, 0), (1, 0), (2, 1), (3, 1), (4, 2), (5, 2), (5, 3), (6, 4)]:
            g[y + dy][x + dx] = 'z'
    return g
lots = [asphalt(21, False), asphalt(24, False), asphalt(25, False), asphalt(26, False)]
stripe = copy(asphalt(22, False))
for y in range(16):
    for x in (7, 8): stripe[y][x] = 'w'
for y in (3, 11): stripe[y][8] = 'W'      # worn paint
stripe_end = copy(asphalt(23, False))
for y in range(0, 12):
    for x in (7, 8): stripe_end[y][x] = 'w'
stripe_end[5][7] = 'W'

out = ["// Cracky — The Lot: sand, dry scrub, asphalt + curbs + parking lines. Generated by tools/gen_lot.py.",
       "(function () {", "const S = Sprout;", "",
       "S.sprite('lot_tiles', {", "  w: 16, h: 16,",
       "  legend: { s: 'sd3', S: 'sd2', D: 'sd1', h: 'sd4', u: 'dr3', v: 'dr2', V: 'dr1' },", "  frames: {"]
for k, g in frames.items(): out.append(js(k, g))
out += ["  },", "});",
        "S.tile('sand', { sprite: 'lot_tiles', frames: ['sand0', 'sand1', 'sand2', 'sand3', 'sand4'], weights: [4, 4, 1, 3, 4] });",
        "// dry scrub = the tall grass art in desert colours",
        "S.recolor('tiles_dry', 'tiles', { a: 'dr0', b: 'dr1', c: 'dr2', e: 'dr3', f: 'dr4' });",
        "S.tile('scrub', { sprite: 'tiles_dry', frame: 'tall0', rustle: 'tall1', over: 'tallOver', grass: true });", ""]
def terr(name, gs, joins):
    if not isinstance(gs[0][0], list): gs = [gs]
    rows = "\n  ], [\n".join(",\n".join(f"    '{''.join(r)}'" for r in g) + "," for g in gs)
    return (f"S.terrain('{name}', {{\n  legend: {{ a: 'as1', b: 'as2', c: 'as3', z: 'as0', w: 'pw1', W: 'pw0' }},\n  fill: [[\n{rows}\n  ]], variants: true,\n"
            f"  bands: {{ top: ['cb0', 'cb3', 'cb2', 'as1'], left: ['cb0', 'cb2', 'as1'], right: ['cb0', 'cb2', 'cb1'], bottom: ['cb0', 'cb2', 'cb1'] }},\n"
            f"  radius: 3, wobble: 0, joins: {joins},\n}});")
out.append(terr('lot', lots, "['lotV', 'lotE']"))
out.append(terr('lotV', stripe, "['lot', 'lotE']"))
out.append(terr('lotE', stripe_end, "['lot', 'lotV']"))
out.append("})();")
open(os.path.join(os.path.dirname(__file__), '..', 'cracky', 'art_tiles.js'), 'w').write("\n".join(out) + "\n")
